//! # axis-commands
//!
//! An independent command framework for the Axis Discord library.
//!
//! ## Planned responsibilities (Phase 5)
//!
//! - Slash command registration (global and per-guild) through the REST API.
//! - Typed command options: string, integer, boolean, user, channel, role,
//!   and mentionable arguments.
//! - Subcommands and subcommand groups.
//! - Interaction handling with immediate, deferred, and ephemeral responses.
//! - Command-level permission requirements.
//! - Autocomplete support.
//! - An optional structured command abstraction for developers who prefer
//!   declaring commands over manually matching on interactions.
//!
//! ## Status
//!
//! Not yet implemented. This crate intentionally contains no APIs yet —
//! see the repository README and `docs/ARCHITECTURE.md` for the plan.
