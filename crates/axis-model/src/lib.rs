//! # axis-model
//!
//! Strongly typed data models for objects exchanged with the Discord API:
//! users, guilds, channels, messages, roles, and so on.
//!
//! ## Design notes
//!
//! - Discord objects change shape depending on context: the same `User`
//!   object appears in full form in `Message.author`, with extra fields in
//!   gateway `Presence Update`, and trimmed down elsewhere. Optional
//!   Discord fields are therefore modeled as `Option<T>`, and unknown
//!   fields are ignored on deserialization rather than rejected — the API
//!   grows new fields over time, and an unknown field must not break a
//!   running bot.
//! - IDs use the typed [`axis_core::id::Id`] wrapper, so a user ID cannot
//!   be confused with a channel ID.
//! - Bitsets (permissions, flags) deserialize leniently: bits the library
//!   does not know about are preserved where harmless.
//! - Documented integer enums (`ChannelType`, `MessageType`, ...) are
//!   generated by the internal [`api_enum`] macro: strict conversion,
//!   number-based serde. An unknown enum value fails deserialization
//!   loudly — for required fields that is better than silently
//!   misinterpreting data.
//!
//! ## Status
//!
//! Phase 2: models needed by the REST client (message, channel, guild,
//! member, role, emoji, embed, attachment, reaction) join the Phase 1
//! `User` model. The remaining model set (interactions, audit log,
//! stickers, ...) arrives with later phases.

/// Generates an enum mirroring a documented Discord integer enum, with
/// `from_value`/`as_value` conversions and number-based serde.
///
/// All JSON integers arrive through serde's `visit_u64`, regardless of the
/// requested width, so deserialization converts through `u64`.
macro_rules! api_enum {
    (
        $(#[$enum_meta:meta])*
        $name:ident: $underlying:ty {
            $(
                $(#[$variant_meta:meta])*
                $variant:ident = $value:expr
            ),* $(,)?
        }
    ) => {
        $(#[$enum_meta])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        #[repr($underlying)]
        pub enum $name {
            $(
                $(#[$variant_meta])*
                $variant = $value,
            )*
        }

        impl $name {
            /// Parse from the documented numeric value.
            pub const fn from_value(value: $underlying) -> Option<Self> {
                match value {
                    $($value => Some(Self::$variant),)*
                    _ => None,
                }
            }

            /// The documented numeric value.
            pub const fn as_value(self) -> $underlying {
                self as $underlying
            }
        }

        impl serde::Serialize for $name {
            fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                serializer.serialize_u64(u64::from(self.as_value()))
            }
        }

        impl<'de> serde::Deserialize<'de> for $name {
            fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                struct EnumVisitor;

                impl<'de> serde::de::Visitor<'de> for EnumVisitor {
                    type Value = $name;

                    fn expecting(
                        &self,
                        formatter: &mut core::fmt::Formatter<'_>,
                    ) -> core::fmt::Result {
                        write!(formatter, "a documented value of {}", stringify!($name))
                    }

                    fn visit_u64<E: serde::de::Error>(
                        self,
                        value: u64,
                    ) -> Result<Self::Value, E> {
                        let value = <$underlying>::try_from(value).map_err(|_| {
                            serde::de::Error::invalid_value(
                                serde::de::Unexpected::Unsigned(value),
                                &self,
                            )
                        })?;
                        Self::Value::from_value(value).ok_or_else(|| {
                            serde::de::Error::invalid_value(
                                serde::de::Unexpected::Unsigned(u64::from(value)),
                                &self,
                            )
                        })
                    }
                }

                deserializer.deserialize_u64(EnumVisitor)
            }
        }
    };
}

